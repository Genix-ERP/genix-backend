-- Account correspondence matrix (шахматка) — which DEBIT account group validly
-- pairs with which CREDIT account group. Codes are account GROUP codes; the
-- correspondence applies to every leaf account under a group (resolved via the
-- chart hierarchy at query time). Seeded from the client's 2025 шахматка.
CREATE TABLE IF NOT EXISTS account_correspondences (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    debit_code  VARCHAR(20) NOT NULL,
    credit_code VARCHAR(20) NOT NULL,
    created_at  TIMESTAMPTZ DEFAULT now(),
    UNIQUE (debit_code, credit_code)
);

